#!/usr/bin/env python3
"""Generate the Android CMVS profile menu from the upstream game registry."""
import argparse
import re
import xml.etree.ElementTree as ET
from pathlib import Path


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    registry = args.source / "crates/cmvs-profile-research/profiles/games.txt"
    contents = registry.read_text(encoding="utf-8")
    ids = re.findall(r"^game ([a-z0-9_-]+)$", contents, re.MULTILINE)
    if not ids or len(set(ids)) != len(re.findall(r"^game ", contents, re.MULTILINE)):
        parser.error("expected unique game IDs in the upstream registry")

    index = (args.source / "docs/games/README.md").read_text(encoding="utf-8")
    titles = {
        game_id: title
        for title, game_id in re.findall(
            r"^\| \[([^\n]+) / ([a-z0-9_-]+)\]\(\2/README\.md\)", index, re.MULTILINE
        )
    }
    resources = ET.Element("resources")
    resources.append(ET.Comment(" Generated by tools/cmvs/export_profiles.py. "))
    keys = ET.SubElement(resources, "string-array", name="cmvs_profile_ids", translatable="false")
    labels = ET.SubElement(resources, "string-array", name="cmvs_profile_titles", translatable="false")
    for game_id in ids:
        ET.SubElement(keys, "item").text = game_id
        title = titles.get(game_id, game_id).replace("\\", "\\\\").replace('"', '\\"').replace("'", "\\'")
        ET.SubElement(labels, "item").text = title
    ET.indent(resources, space="    ")
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        + ET.tostring(resources, encoding="unicode") + "\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
