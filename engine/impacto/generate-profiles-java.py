#!/usr/bin/env python3
"""Generate the Android-independent catalog from the audited native profile authority."""
import hashlib
import json
from pathlib import Path
import sys

root = Path(__file__).resolve().parents[1]
source = root / 'impacto/profiles.json'
target = root / 'src/main/java/com/core/impacto/ImpactoProfiles.java'
raw = source.read_bytes()
catalog = json.loads(raw)
assert catalog['version'] == 1
quote = lambda value: json.dumps(value, ensure_ascii=False)
rows = []
for profile in catalog['profiles']:
    saves = ', '.join('new String[]{' + quote(key) + ', ' + quote(value) + '}' for key, value in profile['saveFields'].items())
    required = ', '.join('new Requirement(' + quote(item['path']) + ', ' + str(item['type'] == 'directory').lower() + ')' for item in profile['required'])
    rows.append('        profiles.put(' + quote(profile['id']) + ', new Profile(' + ', '.join(quote(profile[key]) for key in ['id', 'name', 'lua', 'gamePrefix']) + ', new String[][]{' + saves + '}, new Requirement[]{' + required + '}));')
text = '''package com.core.impacto;

import java.util.Collections;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.ArrayList;

/** Generated by engine/impacto/generate-profiles-java.py. Do not edit the allowlist here.
 * A bundled profile is experimental metadata, not a game-compatibility claim. */
public final class ImpactoProfiles {
    public static final String SOURCE_SHA256 = "''' + hashlib.sha256(raw).hexdigest() + '''";
    public static final class Requirement {
        public final String path;
        public final boolean directory;
        Requirement(String path, boolean directory) { this.path = path; this.directory = directory; }
    }
    public static final class Profile {
        public final String id, name, lua, gamePrefix;
        public final Map<String, String> saveFields;
        public final List<Requirement> required;
        Profile(String id, String name, String lua, String gamePrefix, String[][] saves, Requirement[] required) {
            this.id = id; this.name = name; this.lua = lua; this.gamePrefix = gamePrefix;
            Map<String, String> fields = new LinkedHashMap<>();
            for (String[] field : saves) fields.put(field[0], field[1]);
            this.saveFields = Collections.unmodifiableMap(fields);
            this.required = Collections.unmodifiableList(java.util.Arrays.asList(required));
        }
    }
    private static final Map<String, Profile> PROFILES;
    static {
        Map<String, Profile> profiles = new LinkedHashMap<>();
''' + '\n'.join(rows) + '''
        PROFILES = Collections.unmodifiableMap(profiles);
    }
    private ImpactoProfiles() { }
    public static boolean isSupported(String id) { return PROFILES.containsKey(id); }
    public static String title(String id) { Profile p = get(id); return p == null ? null : p.name; }
    public static Profile get(String id) { return PROFILES.get(id); }
    public static List<String> ids() { return Collections.unmodifiableList(new ArrayList<>(PROFILES.keySet())); }
}
'''
if '--check' in sys.argv:
    if not target.exists() or target.read_text() != text:
        raise SystemExit('ImpactoProfiles.java is stale; run engine/impacto/generate-profiles-java.py')
else:
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(text)
